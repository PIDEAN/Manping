"""Recompute final manifest hashes and test bundle runtime closure with a system-only PATH."""
import argparse
import json
import os
from pathlib import Path
import subprocess

from bundle import ROOT, links, run, sha256, system


# Names of the pre-rename product; none may appear in any Info.plist inside the app.
FORBIDDEN_IDENTITY = ('bilibilimac', 'bilimac', 'bilicore')


def check_identity(app):
    """No test bundles, and no Info.plist that still names the old product."""
    tests = sorted(str(p.relative_to(app)) for p in app.rglob('*Tests.bundle'))
    assert not tests, f'Test bundles in app: {tests}'
    for info in app.rglob('Info.plist'):
        text = info.read_bytes().decode('utf-8', 'replace').lower()
        for name in FORBIDDEN_IDENTITY:
            assert name not in text, f'{info.relative_to(app)} contains "{name}"'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--app', type=Path, default=ROOT / 'dist/release/满屏.app')
    parser.add_argument('--evidence', type=Path, help='Optional legacy report; no report file is generated by default')
    parser.add_argument('--static-only', action='store_true', help='Verify final hashes, architecture, closure and signature without launching renderer diagnostics')
    parser.add_argument('--work-dir', type=Path, default=ROOT / '.build')
    args = parser.parse_args()
    args.work_dir.mkdir(parents=True, exist_ok=True)
    app = args.app.resolve()
    manifest = json.loads((app.parent / 'BundleManifest.json').read_text())
    actual = {str(p.relative_to(app)) for p in (app / 'Contents/Frameworks').glob('*.dylib')}
    actual.update(['Contents/MacOS/Manping', 'Contents/MacOS/ffmpeg'])
    assert len(actual) == len(manifest) == 46
    assert actual == {item['bundledPath'] for item in manifest}
    for item in manifest:
        binary = app / item['bundledPath']
        assert item['signaturePhase'] == 'final-app-signed'
        assert sha256(binary) == item['signedSHA256']
        assert run('lipo', '-archs', str(binary), capture=True) == 'arm64'
        assert links(binary) == item['dependencies']
        for dep in item['dependencies']:
            assert system(dep) or (dep.startswith('@rpath/') and (app / 'Contents/Frameworks' / dep[7:]).exists()), dep
        assert '/opt/homebrew' not in run('otool', '-l', str(binary), capture=True)
    run('codesign', '--verify', '--deep', '--strict', str(app))
    check_identity(app)
    if args.static_only:
        print('PASS: 46 final signed hashes, arm64 architecture, dependency closure, no Homebrew RPATH and strict signature')
        return
    env = dict(os.environ, PATH='/usr/bin:/bin:/usr/sbin:/sbin', DYLD_PRINT_LIBRARIES='1')
    env.pop('MANPING_MPV_LIBRARY', None)
    paths = [(['ffmpeg', '-version'], args.work_dir / 'bundle-ffmpeg-runtime.log'),
             (['Manping', '--diagnose', str(ROOT / '.build/full-pipeline/static.mp4'),
               '--sdr', '--seconds', '2', '--report', str(args.work_dir / 'bundle-runtime.json')], args.work_dir / 'bundle-app-runtime.log')]
    for command, output in paths:
        executable = app / 'Contents/MacOS' / command[0]
        result = subprocess.run([str(executable), *command[1:]], env=env, stdout=subprocess.PIPE,
                                stderr=subprocess.STDOUT, timeout=30, text=True)
        (ROOT / output).write_text(result.stdout)
        assert result.returncode == 0
        loaded = [line for line in result.stdout.splitlines() if line.startswith('dyld[')]
        assert loaded, 'dyld runtime loader evidence missing'
        assert not any('/opt/homebrew/' in line for line in loaded)
        if command[0] == 'Manping':
            assert any(str(app / 'Contents/Frameworks/libmpv.2.dylib') in line for line in loaded)
    evidence = {'buildMode': 'release', 'dylibs': 44, 'machO': 46, 'allArm64': True,
                'allFinalSignedSHA256Verified': True, 'codesignDeepStrict': True,
                'systemPathRuntimeExit0': True, 'noHomebrewLoaded': True}
    if args.evidence: args.evidence.write_text(json.dumps(evidence, indent=2) + '\n')
    print(json.dumps(evidence))


if __name__ == '__main__':
    main()
